#!/usr/bin/env python3
"""Generate src/tables.rs from libvpx's VP8 sources (BSD-3-Clause, The WebM Project authors).

Usage: python3 tools/tables.py <libvpx checkout>/vp8 src/tables.rs
Reads vp8/common/{default_coef_probs.h, coefupdateprobs.h, vp8_entropymodedata.h, entropymv.c,
modecont.c, entropymode.c, quant_common.c}. The values are those of RFC 6386.
"""
import re, sys

src, dst = sys.argv[1], sys.argv[2]

def grab(fn, name, n):
    s = open(f"{src}/common/{fn}").read()
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    i = s.index(name); j = s.index('=', i); k = s.index('};', j)
    nums = [int(x) for x in re.findall(r'\b\d+\b', s[j:k])]
    assert len(nums) == n, (name, len(nums), n)
    return nums

def fmt(nums, dims, ty):
    def rec(a, ds):
        if len(ds) == 1:
            return '[' + ', '.join(map(str, a)) + ']'
        step = len(a) // ds[0]
        return '[' + ', '.join(rec(a[i*step:(i+1)*step], ds[1:]) for i in range(ds[0])) + ']'
    t = ty
    for x in reversed(dims):
        t = f'[{t}; {x}]'
    return t, rec(nums, dims)

out = ["//! VP8's constant tables (RFC 6386). The values are the standard's, taken from libvpx\n"
       "//! (Copyright (c) 2010, The WebM Project authors; BSD-3-Clause, see THIRD-PARTY-NOTICES.txt).\n"
       "//! Generated by `tools/tables.py`; don't edit by hand.\n"]

def emit(rname, fn, cname, dims, ty='u8'):
    n = 1
    for x in dims:
        n *= x
    t, v = fmt(grab(fn, cname, n), dims, ty)
    out.append(f"pub const {rname}: {t} = {v};\n")

emit('COEF_PROBS', 'default_coef_probs.h', 'default_coef_probs', [4, 8, 3, 11])
emit('COEF_UPDATE_PROBS', 'coefupdateprobs.h', 'vp8_coef_update_probs', [4, 8, 3, 11])
emit('YMODE_PROB', 'vp8_entropymodedata.h', 'vp8_ymode_prob[', [4])
emit('KF_YMODE_PROB', 'vp8_entropymodedata.h', 'vp8_kf_ymode_prob', [4])
emit('UV_MODE_PROB', 'vp8_entropymodedata.h', 'vp8_uv_mode_prob[', [3])
emit('KF_UV_MODE_PROB', 'vp8_entropymodedata.h', 'vp8_kf_uv_mode_prob', [3])
emit('BMODE_PROB', 'vp8_entropymodedata.h', 'vp8_bmode_prob[', [9])
emit('KF_BMODE_PROB', 'vp8_entropymodedata.h', 'vp8_kf_bmode_prob', [10, 10, 9])
emit('MV_UPDATE_PROBS', 'entropymv.c', 'vp8_mv_update_probs', [2, 19])
emit('MV_DEFAULT_PROBS', 'entropymv.c', 'vp8_default_mv_context', [2, 19])
emit('MODE_CONTEXTS', 'modecont.c', 'vp8_mode_contexts', [6, 4])
emit('SUB_MV_REF_PROB', 'entropymode.c', 'vp8_sub_mv_ref_prob2', [5, 3])
emit('MBSPLITS', 'entropymode.c', 'vp8_mbsplits[', [4, 16])
emit('MBSPLIT_PROBS', 'entropymode.c', 'vp8_mbsplit_probs', [3])
emit('DC_Q', 'quant_common.c', 'dc_qlookup', [128], 'u16')
emit('AC_Q', 'quant_common.c', 'ac_qlookup', [128], 'u16')
open(dst, 'w').write('\n'.join(out))
